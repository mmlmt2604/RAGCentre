// Generate src/api/generated/openapi.ts from the backend's OpenAPI document (IMPLEMENTATION_PLAN.md M11).
// Usage: npm run types:api   (needs uv and the Python project one directory up)
// src/api/contract-check.ts then type-checks the generated types against the hand-written contract
// in src/api/types.ts, so `npm run typecheck` fails when the backend and the contract drift apart.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const ui = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const json = execFileSync("uv", ["run", "--quiet", "python", "-m", "ragcentre.api.openapi"], {
  cwd: resolve(ui, ".."),
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
// defaultNonNullable: false keeps request fields that have defaults optional. Response models mark
// every field required in the schema themselves (ResponseModel in ragcentre/models/api.py).
const ast = await openapiTS(JSON.parse(json), { defaultNonNullable: false });
const header =
  "// Generated by `npm run types:api` from the backend's OpenAPI document. Do not edit.\n";
const out = resolve(ui, "src/api/generated/openapi.ts");
writeFileSync(out, header + astToString(ast));
console.log(`wrote ${out}`);
